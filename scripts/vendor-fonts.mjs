/**
 * Copy the bundled reading fonts out of unpacked @fontsource packages into
 * assets/fonts/ and write src/settings/font-catalog.ts. Run it again only to
 * change the font list; the output is committed, so builds stay offline.
 *
 *   npm pack @fontsource/literata@5.3.0 && tar xzf ... -C <dir>
 *   node scripts/vendor-fonts.mjs <dir with one unpacked package per font>
 *
 * Every font here is under the SIL Open Font License 1.1; each one's licence
 * is copied next to its files.
 */
import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";

/** id, the fontsource package, the label shown in the reader, and the CSS fallback. */
const FONTS = [
  { id: "literata", pkg: "literata", label: "Literata", kind: "serif" },
  { id: "garamond", pkg: "eb-garamond", label: "Garamond", kind: "serif" },
  { id: "atkinson", pkg: "atkinson-hyperlegible", label: "Atkinson", kind: "sans-serif" },
  { id: "opendyslexic", pkg: "opendyslexic", label: "OpenDyslexic", kind: "sans-serif" },
];
const SUBSETS = ["latin", "latin-ext", "cyrillic", "cyrillic-ext", "greek"];
const WEIGHTS = [400, 700];
const STYLES = ["normal", "italic"];

const source = process.argv[2];
if (!source) throw new Error("usage: node scripts/vendor-fonts.mjs <dir>");
const root = new URL("..", import.meta.url).pathname;
const out = join(root, "assets/fonts");
rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });

function packageDir(pkg) {
  const name = readdirSync(source).find((entry) => entry.startsWith(`fontsource-${pkg}-`) && !entry.endsWith(".tgz"));
  if (!name) throw new Error(`no unpacked @fontsource/${pkg} in ${source}`);
  return join(source, name, "package");
}

const catalog = [];
for (const font of FONTS) {
  const dir = packageDir(font.pkg);
  const meta = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
  if (meta.license !== "OFL-1.1") throw new Error(`${font.pkg} is ${meta.license}, not OFL-1.1`);
  const ranges = existsSync(join(dir, "unicode.json")) ? JSON.parse(readFileSync(join(dir, "unicode.json"), "utf8")) : {};
  const faces = [];
  for (const subset of SUBSETS) {
    for (const weight of WEIGHTS) {
      for (const style of STYLES) {
        const file = `${font.pkg}-${subset}-${weight}-${style}.woff2`;
        if (!existsSync(join(dir, "files", file))) continue;
        const target = `${font.id}-${subset}-${weight}-${style}.woff2`;
        copyFileSync(join(dir, "files", file), join(out, target));
        // A font with one subset has no unicode.json entry; it covers whatever it has.
        faces.push({ file: target, weight, style, range: ranges[subset] ?? null });
      }
    }
  }
  if (faces.length === 0) throw new Error(`no faces for ${font.pkg}`);
  copyFileSync(join(dir, "LICENSE"), join(out, `${font.id}.LICENSE.txt`));
  catalog.push({ id: font.id, label: font.label, kind: font.kind, version: meta.version, faces });
}

const lines = [
  "// Generated by scripts/vendor-fonts.mjs. Do not edit; run the script again.",
  'import type { BundledFont } from "./fonts.ts";',
  "",
  `export const BUNDLED_FONTS: readonly BundledFont[] = ${JSON.stringify(catalog, null, 2)};`,
  "",
];
writeFileSync(join(root, "src/settings/font-catalog.ts"), lines.join("\n"));
console.log(`vendored ${catalog.length} fonts, ${catalog.reduce((n, f) => n + f.faces.length, 0)} files, to assets/fonts`);
